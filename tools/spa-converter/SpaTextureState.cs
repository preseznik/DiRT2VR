using System.Text.Json;
using DiRT2VR.Nordschleife;
using EgoEngineLibrary.Graphics.Pssg.Elements;

internal static class SpaTextureState
{
    internal static void Preserve(string output,string source)
    {
        using var report=JsonDocument.Parse(File.ReadAllBytes(Path.Combine(output,"texture-bindings.json")));
        var states=new Dictionary<string,(int S,int T)>();
        foreach(var entry in report.RootElement.EnumerateArray())
        {
            string hash=entry.GetProperty("DdsHash").GetString()!;
            var pair=(entry.GetProperty("WrapS").GetInt32(),entry.GetProperty("WrapT").GetInt32());
            if(states.TryGetValue(hash,out var previous)&&previous!=pair)throw new InvalidDataException("Shared source pixels have conflicting addressing; separate these textures: "+hash);
            states[hash]=pair;
        }
        string path=Path.Combine(output,"shared/tracksplit.pssg");var pssg=Files.Pssg(path);var changes=new List<object>();
        foreach(var texture in pssg.Elements<PssgTexture>().Where(t=>t.Id.StartsWith("nord_tex_",StringComparison.Ordinal)))
        {
            var pair=states.Single(p=>texture.Id.StartsWith("nord_tex_"+p.Key[..20],StringComparison.Ordinal)).Value;
            changes.Add(new{texture.Id,OldS=texture.WrapS,OldT=texture.WrapT,SourceS=pair.S,SourceT=pair.T});
            texture.WrapS=pair.S;texture.WrapT=pair.T;
        }
        // Accepted fence repairs kept the source alpha mips and sampler state.
        // Preserve the complete texture rather than the donor's filtering defaults.
        foreach(var entry in report.RootElement.EnumerateArray().Where(e=>SpaFenceRepair.IsCoverageTexture(e.GetProperty("Reference").GetString()!)).DistinctBy(e=>e.GetProperty("DdsHash").GetString()))
        {
            string id="nord_tex_"+entry.GetProperty("DdsHash").GetString()![..20];
            var target=pssg.GetObject<PssgTexture>(id.AsMemory());
            var original=Files.Pssg(Files.Inside(source,"tracks/locations/europe/spa_francorchamps/"+entry.GetProperty("ResolvedFile").GetString()));
            var replacement=(PssgTexture)original.GetObject<PssgTexture>(entry.GetProperty("Texture").GetString()!.AsMemory()).DeepClone();
            replacement.Id=id;var parent=target.ParentElement!;parent.RemoveChild(target);parent.AppendChild(replacement);
        }
        // This file is freshly generated by this build, not an installed asset.
        using(var stream=new FileStream(path,FileMode.Truncate))pssg.Save(stream);
        var saved=Files.Pssg(path);
        foreach(var texture in saved.Elements<PssgTexture>().Where(t=>t.Id.StartsWith("nord_tex_",StringComparison.Ordinal)))
        {var pair=states.Single(p=>texture.Id.StartsWith("nord_tex_"+p.Key[..20],StringComparison.Ordinal)).Value;if(texture.WrapS!=pair.S||texture.WrapT!=pair.T)throw new InvalidDataException("Addressing readback failed");}
        Files.Json(Path.Combine(output,"texture-addressing.json"),new{Passed=true,Textures=changes,SourceAddressingRestored=true});
    }
}
